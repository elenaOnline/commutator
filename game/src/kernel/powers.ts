// LEMMA WORKS kernel — the IMPORTED integer-power library (v4 Phase B, sol-exponents.md §3).
//
// These statements are true in every group for all integers (Mathlib zpow_add, zpow_mul, zpow_neg,
// inv_zpow, …; the conjugation law is proved externally in §3). The kernel checks USES of them; it does
// not derive them. Their authority is kernel-owned: a registry entry with the same id is ignored, and a
// level enables one only by listing its id in tools.schemas ('power.literal' enables the whole
// literal family power.literal:<r>).
import type { Card, Schema, Term } from './types';
import { E, KErr, inv, meta, mul, norm, pow as repeatWordOf } from './terms';
import { POLY_LIMITS, ResourceLimit, polyAdd, polyConst, polyMul, polyNeg, polyZmeta } from './poly';

const x = meta('x'), u = meta('u'), v = meta('v');
const m = polyZmeta('m'), n = polyZmeta('n');
const P = (base: Term, exp: ReturnType<typeof polyConst>): Term => norm({ k: 'pow', base, exp });
const law = (metas: string[], l: Term, r: Term): Card => ({ k: 'law', metas, l: norm(l), r: norm(r) });
const imp = (id: string, name: string, textbook: string, card: Card, mirrorable = false): Schema =>
  ({ id, name, textbook, card, origin: 'import', mirrorable });

/** The fixed imported power laws. Merge into the game REGISTRY for listing; the kernel resolves them itself. */
export const POWER_SCHEMAS: Record<string, Schema> = {
  'power.add': imp('power.add', 'product of powers', 'xᵐxⁿ = xᵐ⁺ⁿ (imported)',
    law(['x', 'm', 'n'], mul([P(x, m), P(x, n)]), P(x, polyAdd(m, n)))),
  'power.multiply': imp('power.multiply', 'power of a power', '(xᵐ)ⁿ = xᵐⁿ (imported)',
    law(['x', 'm', 'n'], P(P(x, m), n), P(x, polyMul(m, n)))),
  'power.zero': imp('power.zero', 'zeroth power', 'x⁰ = e (imported)', law(['x'], P(x, polyConst(0)), E)),
  'power.one': imp('power.one', 'first power', 'x¹ = x (imported)', law(['x'], P(x, polyConst(1)), x)),
  'power.identity': imp('power.identity', 'power of e', 'eⁿ = e (imported)', law(['n'], P(E, n), E)),
  'power.inverseBase': imp('power.inverseBase', 'power of an inverse', '(x⁻¹)ⁿ = x⁻ⁿ (imported)',
    law(['x', 'n'], P(inv(x), n), P(x, polyNeg(n)))),
  'power.negate': imp('power.negate', 'negative power', 'x⁻ⁿ = (xⁿ)⁻¹ (imported)',
    law(['x', 'n'], P(x, polyNeg(n)), inv(P(x, n)))),
  'power.conjugate': imp('power.conjugate', 'power of a conjugate', '(u⁻¹vu)ⁿ = u⁻¹vⁿu (imported)',
    law(['u', 'v', 'n'], P(mul([inv(u), v, u]), n), mul([inv(u), P(v, n), u])), true),
};

export const POWER_LITERAL_FAMILY = 'power.literal';
const LITERAL_ID = /^power\.literal:(-?\d+)$/;

/** The literal of a power.literal:<r> id, or null when the id is not of that family. */
export function literalOf(id: string): bigint | null {
  const mm = LITERAL_ID.exec(id);
  return mm ? BigInt(mm[1]!) : null;
}

/** power.literal(r): ∀x. x^r = (r ordered copies of x). Generated by the kernel; r checked. */
export function powerLiteralSchema(r: bigint): Schema {
  if (r > BigInt(POLY_LIMITS.literalPower)) throw new ResourceLimit(`a power over ${POLY_LIMITS.literalPower} factors is too big to expand.`);
  if (r < 1n) throw new KErr(`Literal power needs a whole number above 0. For ${r}, use zeroth power or negative power.`);
  const k = Number(r);
  return imp(`power.literal:${k}`, `literal power ${k}`, `x^${k} = ${k} copies of x (imported)`,
    law(['x'], P(x, polyConst(k)), k === 1 ? x : repeatWordOf(x, k)));
}

/** Kernel-owned import resolution (null if the id is not a power import). */
export function powerSchema(id: string): Schema | null {
  if (POWER_SCHEMAS[id]) return POWER_SCHEMAS[id]!;
  const r = literalOf(id);
  if (r !== null) return powerLiteralSchema(r);
  if (id.startsWith('power.')) throw new KErr(`There is no imported power law “${id}”.`);
  return null;
}

/** Is a power import enabled in this level? */
export function powerAllowed(id: string, schemas: string[]): boolean {
  return schemas.includes(id) || (literalOf(id) !== null && schemas.includes(POWER_LITERAL_FAMILY));
}
